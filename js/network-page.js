const esc = (s) => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const nr = (what = 'not recorded') => `<span class="nx-nr">${esc(what)}</span>`;
const strip = (html) => String(html).replace(/<[^>]+>/g, '');

/* ---------------------------------------------------------- words */

const shortOf = (ix, id) => ix.instrument.get(id)?.short_name || id;

/** The kind as the site words it: "Proposed: amends" when the stating act is not adopted. */
const kindWords = (ix, r) => kindText(r, ix, label(ix, r.kind) || kindKey(r.kind));

/** Type and direction in words; a direction only where the record gives one. */
export function directionWords(ix, r) {
  const a = esc(shortOf(ix, r.from)), b = esc(shortOf(ix, r.to)), k = esc(kindWords(ix, r));
  if (r.symmetric === true) return `${k} — mutual, no direction: ${a} and ${b}`;
  if (r.symmetric === false) return `${k} — from ${a} to ${b}`;
  return `${k} — ${a} and ${b}: ${nr('direction not recorded')}`;
}

function nodeLabel(ix, counts, inst) {
  const n = counts.touching.get(inst.id).length;
  const cov = coverage(inst);
  return `${inst.short_name}, ${label(ix, inst.kind) || 'instrument'}; ${cov || 'coverage not recorded'}; ` +
    (n ? F.plural(n, 'relationship') + ' recorded' : 'no relationship recorded');
}

/* ---------------------------------------------------------- SVG pieces */

const markers = (prefix, kinds) => '<defs>' + kinds.map((k) =>
  `<marker id="${prefix}-${kindKey(k)}" class="nx-mk f-${kindFamily(k)}" viewBox="0 0 10 10" refX="8.5" refY="5" markerUnits="userSpaceOnUse" markerWidth="11" markerHeight="11" orient="auto"><path d="M0,0.5 L10,5 L0,9.5 z"/></marker>`).join('') + '</defs>';

function edgeSvg(ix, r, geo, prefix) {
  const dash = kindDash(r.kind);
  const arrow = r.symmetric === false ? ` marker-end="url(#${prefix}-${kindKey(r.kind)})"` : '';
  const proposed = modality(r, ix) === 'proposed';
  return `<g class="edge f-${kindFamily(r.kind)}${proposed ? ' proposed' : ''}" data-rel="${esc(r.id)}" data-kind="${esc(r.kind)}" aria-hidden="true"><title>${esc(strip(directionWords(ix, r)))}</title>` +
    `<path class="e-line"${dash ? ` stroke-dasharray="${dash}"` : ''} d="${geo.d}"${arrow}/>` +
    `<path class="e-hit" d="${geo.d}"/>` +
    `<g class="e-badge"><rect x="${(geo.mid.x - 10).toFixed(1)}" y="${(geo.mid.y - 6.5).toFixed(1)}" width="20" height="13" rx="2"/>` +
    `<text x="${geo.mid.x.toFixed(1)}" y="${(geo.mid.y + 3).toFixed(1)}">${esc(kindCode(r.kind))}</text></g></g>`;
}

function nodeSvg(ix, counts, inst, p, { labelSide = 'right' } = {}) {
  const cov = coverage(inst) || 'none';
  const below = labelSide === 'below';
  const text = `<text x="${below ? 0 : NODE_R + 5}" y="${below ? NODE_R + 15 : 4}" text-anchor="${below ? 'middle' : 'start'}">${esc(inst.short_name)}</text>`;
  return `<g class="node c-${cov}" data-id="${esc(inst.id)}" role="button" tabindex="-1" aria-pressed="false" aria-label="${esc(nodeLabel(ix, counts, inst))}" transform="translate(${p.x.toFixed(1)},${p.y.toFixed(1)})">` +
    `<circle class="n-ring" r="${NODE_R + 5}"/><circle class="n-dot" r="${NODE_R}"/>${text}</g>`;
}

