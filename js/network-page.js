/* ============================================================
   The network of the instruments — network.html.

   The Regulatory Network Explorer the author chose on 13 Nov 2026 (the
   Hybrid's layout with the observatory's 3D network in its box,
   docs/PROTOTYPES.md §3.6), brought to production on its own page by the
   network-map session (docs/ROADMAP-v2.md §8, 23 Nov 2026: the map alone,
   the full combination, on network.html, noindex until it has been
   measured on a real phone).

   What it shows, and nothing else: the instruments of
   data/instruments.json as nodes and its `relationships` as edges, through
   js/data.js. js/network-model.js derives the counts and the layout. Two
   things it takes from the site rather than from the prototype, so that a
   relationship reads one way on every page:
   - the kind's words: js/map-model.js kindText() — an edge whose stating
     act is not adopted is "Proposed: amends", never "amends" alone
     (V2C-01). Such an edge is also drawn faint and thin with its code in a
     dashed box, so the difference is not carried by the words alone;
   - the relationship itself: js/interactions.js, the block the brief and
     the instrument pages render — in the panel, in the table under the
     network, and (generated by tools/_footer.mjs) in the list a reader
     without JavaScript gets.

   Layout. From 52rem: the selection panel and the table on the left (the
   table leads), the network in a box on the right with its controls above
   and its legend below. "Enlarge the network" gives the stage the full
   width with the panel inside it; the same button, or Esc outside the
   canvas, returns. Below 52rem the canvas is not shrunk: an ego view draws
   the selected instrument and its direct relationships.

   data/brief.json is read for the parts' ids, kinds and numerals only — to
   group by part and to say "Part V", linked to that part of the brief. A
   part's TITLE is never printed here: brief.json's titles are the one
   second home of the brief's text (AGENTS.md, "Known hazards"), and the
   reader is sent to the markup, which is the first (docs/ROADMAP-v2.md §8,
   23 Nov 2026, network map, decision 4).

   Nothing moves by itself: the reader turns the network (drag, the turn
   buttons, Shift and an arrow key), so prefers-reduced-motion holds
   without a branch.
   ============================================================ */

